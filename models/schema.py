from pydantic import BaseModel, Field
from typing import Annotated, Literal
from langgraph.graph.message import add_messages


class AgentSchema(BaseModel):
    messages: Annotated[list, add_messages] = Field(
        ... , description="List of messages to be processed by agent."
    )
    user_question: str = Field(
        ..., description="The original question asked by the user."
    )
    curated_ques: str = Field(default="", description="Curated user question")
    prompt_query_context: str = Field(
        default="",
        description="A detailed prompt with SQL DB context that helps agent generate SQL Query.",
    )
    is_safe: Literal["Yes", "No"] = Field(
        default="No",
        description="Indicates whether the generated SQL Query is safe to execute or not.",
    )
    generated_sql_query: str = Field(
        default="", description="The SQL query generated by agent."
    )
    sql_query_execution_result: str = Field(
        default="", description="The result of executing the generated SQL query."
    )
    final_answer: str = Field(
        default="", description="The final answer generated by the agent."
    )


class CuratedQuestion(BaseModel):
    curated_question: str = Field(
        description="Refined, unambiguous, self-contained version of the user's question."
    )

class JudgeSchema(BaseModel):
    answer: Literal["Yes", "No"] = Field(..., description="Indicates whether the generated SQL query is safe to execute or not")
    comments: str = Field(..., description="Additional comments or feedback from the judge regarding the SQL query")

class ETLAgentSchema(BaseModel):
    messages: Annotated[list, add_messages] = Field(..., description="List of messages processed by the ETL Agent.")

class RouterSchema(BaseModel):
    answer: Literal["sql", "etl"] = Field(..., description="Indicates whether the user's question related to SQL or ETL operations")

class DataAgentSchema(BaseModel):
    messages: Annotated[list, add_messages] = Field(..., description="List of messages processed by the Data Agent.")
    route_response : str = Field(default="", description="The response from the router indicating whether to route to SQL or ETL operations")

